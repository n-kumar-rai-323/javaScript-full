const light = ("red")
let colour = light.toUpperCase()
switch (colour){
    case "RED":
        console.log("STOP!!");
        break;
    case "YELLOW":
        console.log("READY!!")
        break;
    case "GREEN":
        console.log("GOO!")
        break;
    default:
        console.log("error:")      
        break      
}